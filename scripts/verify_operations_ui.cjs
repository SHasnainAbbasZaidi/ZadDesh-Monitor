const fs=require('node:fs'); const {chromium}=require('../web/node_modules/playwright');
(async()=>{
 const token=process.env.ZADDESH_LIVE_TEST_TOKEN;if(!token)throw new Error('Set ZADDESH_LIVE_TEST_TOKEN to a temporary admin session token.');fs.mkdirSync('.audit/ui-polish',{recursive:true});fs.mkdirSync('.audit/local-run',{recursive:true});
 const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
 const context=await browser.newContext({viewport:{width:1440,height:1000},colorScheme:'dark'});
 await context.addInitScript(value=>localStorage.setItem('zaddesh_token',value),token);
 const page=await context.newPage(); const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('response',r=>{if(r.url().includes('/api/')&&r.status()>=500)errors.push(`${new URL(r.url()).pathname}: ${r.status()}`);});
 await page.goto('http://127.0.0.1:18875/');
 await page.getByRole('heading',{name:'Infrastructure overview',exact:true}).waitFor({timeout:60000});
 const nav=page.getByRole('navigation',{name:'Main navigation'});
 await nav.getByRole('button',{name:'Live Endpoint Trace',exact:true}).click();
 await page.getByRole('heading',{name:'Live endpoint tracing',exact:true}).waitFor();
 await page.getByRole('searchbox').count();
 await page.getByLabel('Search endpoint by username, MAC or IP').fill('192.0.2.254');
 await page.getByText('Loading endpoint observations…',{exact:true}).waitFor({state:'hidden',timeout:60000});
 await page.screenshot({path:'.audit/ui-polish/operations-endpoints.png',fullPage:true});
 await nav.getByRole('button',{name:'Custom Dashboards',exact:true}).click();
 await page.getByRole('heading',{name:'Custom dashboards',exact:true}).waitFor();
 await page.getByLabel('New dashboard name').fill('Operations verification');
 const createdResponse=page.waitForResponse(r=>r.url().endsWith('/dashboard-tools/dashboards')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'Create dashboard',exact:true}).click();
 const createdId=(await (await createdResponse).json()).id;
 await page.waitForFunction(id=>document.querySelector('[aria-label="Selected custom dashboard"]')?.value===String(id),createdId);
 await page.getByText('Loading saved widgets…',{exact:true}).waitFor({state:'hidden'});
 await page.getByRole('button',{name:'Save layout',exact:true}).waitFor();
 await page.getByLabel('Widget type').selectOption('diagram');
 const diagrams=page.getByLabel('Widget diagram');
 await diagrams.locator('option').nth(1).waitFor({state:'attached'});
 await diagrams.selectOption({index:1});
 await page.getByLabel('Title',{exact:true}).fill('Live network topology');
 await page.getByRole('button',{name:'Add widget',exact:true}).click();
 await page.getByLabel('Widget 1 title',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Save layout',exact:true}).click();
 await page.getByText('Dashboard saved.',{exact:true}).waitFor();
 const saved=await page.request.get(`http://127.0.0.1:8000/api/v1/dashboard-tools/dashboards/${await page.getByLabel('Selected custom dashboard').inputValue()}/widgets`,{headers:{Authorization:'Bearer '+token}});
 if((await saved.json()).length!==1)throw new Error('Saved widget missing from MongoDB');
 await page.locator('.custom-widget canvas').first().waitFor({timeout:60000});
 await page.getByLabel('Pin to Overview').check();await page.waitForTimeout(1500);
 await page.screenshot({path:'.audit/ui-polish/operations-builder.png',fullPage:true});
 const id=await page.getByLabel('Selected custom dashboard').inputValue();
 await nav.getByRole('button',{name:'Overview',exact:true}).click();
 await page.getByRole('region',{name:'Operations verification',exact:true}).waitFor({timeout:30000});
 await page.getByRole('region',{name:'Operations verification',exact:true}).locator('canvas').first().waitFor({timeout:60000});
 await page.waitForTimeout(4000);
 await page.screenshot({path:'.audit/ui-polish/operations-overview-dark.png',fullPage:true});
 for(const width of [768,390]){
   await page.setViewportSize({width,height:1000});
   await page.waitForTimeout(600);
   const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+1);
   if(overflow) throw new Error(`Page overflows at ${width}px`);
   await page.screenshot({path:`.audit/ui-polish/operations-${width}.png`,fullPage:true});
 }
 await page.setViewportSize({width:1440,height:1000});
 await page.emulateMedia({colorScheme:'light'});await page.waitForTimeout(600);
 await page.screenshot({path:'.audit/ui-polish/operations-overview-light.png',fullPage:true});
 // Remove only the dashboard created by this verification run.
 const headers={Authorization:'Bearer '+token,'Content-Type':'application/json'};
 const deleted=await page.request.delete(`http://127.0.0.1:8000/api/v1/dashboard-tools/dashboards/${id}`,{headers});
 if(!deleted.ok())throw new Error('Verification dashboard cleanup failed');
 fs.writeFileSync('.audit/local-run/operations-browser.json',JSON.stringify({passed:errors.length===0,errors,viewports:[1440,768,390],dashboardId:Number(id)},null,2));
 console.log(JSON.stringify({passed:errors.length===0,errors,viewports:[1440,768,390]}));
 await browser.close();if(errors.length)process.exitCode=1;
})().catch(e=>{console.error(e.message);process.exit(1);});
